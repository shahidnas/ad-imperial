/**
 * Builds a Bootstrap Icons subset containing only the icons the site uses.
 *
 * The full package ships ~100 KB of render-blocking CSS and a 131 KB font
 * for ~2,000 icons; the site uses about a dozen. Run this after adding a new
 * `bi-*` icon anywhere in the code:
 *
 *   node scripts/build-icon-subset.mjs
 *
 * Requires Python with fontTools + brotli (`pip install fonttools brotli`).
 * Output: src/styles/bootstrap-icons-subset.css and .woff2 (both committed).
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const pkg = path.join(root, "node_modules/bootstrap-icons/font");
const outDir = path.join(root, "src/styles");

// Icons that are built dynamically (e.g. `bi ${social.icon}` in the footer)
// can't be found by scanning, so list the ones that may be configured.
const ALWAYS_INCLUDE = [
  "bi-instagram",
  "bi-facebook",
  "bi-youtube",
  "bi-linkedin",
  "bi-twitter-x",
  "bi-whatsapp",
];

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return /\.(tsx?|css)$/.test(entry.name) ? [full] : [];
  });
}

const used = new Set(ALWAYS_INCLUDE);
for (const file of [...walk(path.join(root, "app")), ...walk(path.join(root, "src"))]) {
  if (file.includes("bootstrap-icons-subset")) continue;
  for (const match of fs.readFileSync(file, "utf8").matchAll(/\bbi-[a-z0-9-]+/g)) used.add(match[0]);
}

const codepoints = JSON.parse(fs.readFileSync(path.join(pkg, "bootstrap-icons.json"), "utf8"));
const icons = [...used]
  .map((cls) => cls.slice(3))
  .filter((name) => codepoints[name] !== undefined)
  .sort();

fs.mkdirSync(outDir, { recursive: true });
const fontOut = path.join(outDir, "bootstrap-icons-subset.woff2");
execFileSync("python", [
  "-m",
  "fontTools.subset",
  path.join(pkg, "fonts/bootstrap-icons.woff2"),
  `--unicodes=${icons.map((name) => codepoints[name].toString(16)).join(",")}`,
  "--flavor=woff2",
  "--no-hinting",
  `--output-file=${fontOut}`,
]);

const css = `/*!
 * Bootstrap Icons v1.13.1 subset (https://icons.getbootstrap.com/) — MIT licence.
 * GENERATED by scripts/build-icon-subset.mjs. Do not edit by hand.
 * Icons: ${icons.join(", ")}
 */

@font-face {
  font-display: block;
  font-family: "bootstrap-icons";
  src: url("./bootstrap-icons-subset.woff2") format("woff2");
}

.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {
  display: inline-block;
  font-family: bootstrap-icons !important;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  vertical-align: -.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${icons.map((name) => `.bi-${name}::before { content: "\\${codepoints[name].toString(16)}"; }`).join("\n")}
`;
fs.writeFileSync(path.join(outDir, "bootstrap-icons-subset.css"), css);

console.log(`${icons.length} icons → ${fs.statSync(fontOut).size} byte font`);
